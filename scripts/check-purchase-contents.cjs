const assert = require('node:assert/strict');
const load = require('./lib/load-project.cjs')({'react': {cache: fn => fn}});
const {PRODUCTS, getProduct} = load('@/data/products');
const {purchaseContents} = load('@/lib/purchase-contents');
const {isRetiredProduct} = load('@/lib/retired-products');
const {studioPieces} = load('@/lib/styleStudio');
const {currentImageSource,showsFullOutfit} = load('@/lib/product-media');
const {seedStore, publicStore} = load('@/lib/server/store-repository');
const {saveProduct, createOrder} = load('@/lib/server/store-actions');
const removed = 'midnight-flow-maxi-skirt';
assert(isRetiredProduct(removed));
assert.equal(getProduct(removed), undefined);
assert(PRODUCTS.every(p => !p.styleWith?.includes(removed)));
assert(studioPieces(PRODUCTS).bottoms.every(p => p.id !== removed));
const trousers = getProduct('botanic-rose-trousers');
assert.match(trousers.name, /Trousers Only/);
assert.equal(trousers.soldSeparately, true);
assert.equal(trousers.priceAud, 185);
assert.equal(trousers.image, trousers.gallery[0]);
assert.equal(trousers.imageHover, trousers.gallery[0]);
assert.match(trousers.galleryLabels[0], /Full outfit styling/);
assert(showsFullOutfit(trousers));
assert.equal(showsFullOutfit(getProduct('cacao-satin-cami')),false);
for(const kind of ['card','hover'])assert.equal(currentImageSource(`/images/bindi-real/botanic-rose-trousers-${kind}-v2.webp`),trousers.gallery[0]);
assert.equal(purchaseContents(trousers).label, 'Trousers only');
assert.match(purchaseContents(trousers).detail, /not the full outfit/);
assert.equal(purchaseContents(getProduct('tea-leaf-two-piece')).label, 'Full two-piece set');
assert.equal(purchaseContents(getProduct('sunlit-paisley-shorts')).label, 'Shorts only');
assert.equal(purchaseContents(getProduct('cacao-satin-cami')).label, 'Top only');
assert.equal(purchaseContents(getProduct('sage-shirt-maxi-dress')), null);
const state = seedStore();
const stale = {...trousers, id: removed, status: 'active'};
state.products.push(stale);
assert(publicStore(state).products.every(p => p.id !== removed));
assert.throws(() => saveProduct(state, stale), /withdrawn|retired|removed/i);
state.settings.acceptingOrders = true;
assert.throws(() => createOrder(state, {requestId: 'retired-check', customer: {email:'qa@example.test', name:'QA', address:'QA address'}, items:[{productId:removed, size:stale.sizes[0], quantity:1}]}), /available|removed|withdrawn/i);
// Existing saved baskets and favourites also drop the withdrawn listing.
const memory = new Map();
global.window = {localStorage:{getItem:key => memory.get(key) ?? null}, dispatchEvent:()=>{}};
memory.set('bindy-cart', JSON.stringify([{product:stale, size:stale.sizes[0], quantity:1}]));
memory.set('bindy-wishlist', JSON.stringify([removed]));
assert.equal(load('@/lib/cart').getCart().length, 0);
assert.equal(load('@/lib/wishlist').getWishlist().length, 0);
delete global.window;
console.log('PASS: removal across catalogue, recommendations, fitting room, old carts/wishlists, admin republishing and checkout; full outfit photo, unchanged trousers price and explicit purchase contents.');
